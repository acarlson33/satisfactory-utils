// Helper functions
export const getRecipeById = (id: string): Recipe | undefined => {
  return recipes.find((recipe) => recipe.id === id);
};

export const getRecipesByBuilding = (buildingId: string): Recipe[] => {
  return recipes.filter((recipe) => recipe.buildingId === buildingId);
};

export const getRecipesByOutput = (itemId: string): Recipe[] => {
  return recipes.filter((recipe) =>
    recipe.outputs.some((output) => output.itemId === itemId)
  );
};

export const getRecipesByInput = (itemId: string): Recipe[] => {
  return recipes.filter((recipe) =>
    recipe.inputs.some((input) => input.itemId === itemId)
  );
};

export const getAlternateRecipes = (): Recipe[] => {
  return recipes.filter((recipe) => recipe.isAlternate);
};

export const getDefaultRecipes = (): Recipe[] => {
  return recipes.filter((recipe) => !recipe.isAlternate);
};

export const searchRecipes = (query: string): Recipe[] => {
  const lower = query.toLowerCase();
  return recipes.filter(
    (recipe) =>
      recipe.name.toLowerCase().includes(lower) ||
      recipe.id.includes(lower) ||
      recipe.outputs.some((o) => o.itemId.includes(lower))
  );
};

/**
 * Calculate items per minute for a recipe
 */
export const getRecipeRate = (
  recipe: Recipe
): { inputs: RecipeIO[]; outputs: RecipeIO[] } => {
  const multiplier = 60 / recipe.craftTime;
  return {
    inputs: recipe.inputs.map((i) => ({
      ...i,
      amount: i.amount * multiplier,
    })),
    outputs: recipe.outputs.map((o) => ({
      ...o,
      amount: o.amount * multiplier,
    })),
  };
};
